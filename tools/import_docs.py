#!/usr/bin/env python3
"""Convert practice-exam Markdown (## M.n headings, **k.** question, '- a. option', '## เฉลย' key) to js/data/bank.js."""
import re, sys, json, html, pathlib
out = []
for path in sys.argv[1:]:
    body, _, key = pathlib.Path(path).read_text(encoding='utf8').partition('## เฉลย')
    keys = {int(m[1]): {int(n): 'abcd'.index(l) for n, l in re.findall(r'(\d+)-([a-d])', m[2])}
            for m in re.finditer(r'\*\*M\.(\d+):\*\*\s*(.+)', key)}
    parts = re.split(r'(?m)^## M\.(\d+)[^\n]*\n', body)
    for mid, text in zip(parts[1::2], parts[2::2]):
        mid = int(mid)
        for m in re.finditer(r'\*\*(\d+)\.\*\*\s*(.+?)\n+((?:- [a-d]\. .+\n?)+)', text):
            opts = [html.escape(o.replace('`', '')) for o in re.findall(r'- [a-d]\. (.+)', m[3])]
            a = keys.get(mid, {}).get(int(m[1]))
            if a is not None and len(opts) == 4:
                out.append({'m': mid, 'q': html.escape(m[2].replace('`', '')), 'c': opts, 'a': a, 'e': ''})
print('/* generated by tools/import_docs.py */\nwindow.BANK=' + json.dumps(out, ensure_ascii=False) + ';')
print(f'{len(out)} questions', file=sys.stderr)
